import type { NextConfig } from 'next'

/**
 * The subset of a site's configuration that Next.js itself needs at build time.
 *
 * Deliberately structural rather than importing `SiteConfig` from `@makleri/core`:
 * `next.config.ts` is loaded before the module graph is resolved, so this package
 * must stay dependency-free.
 */
export interface NextConfigInput {
  /** Canonical production origin, e.g. `https://novakreality.cz`. */
  siteUrl: string
  /** Payload origin serving the REST API, e.g. `https://cms.makleri.cz`. */
  cmsUrl: string
  /**
   * Origin serving uploaded media. Normally the R2 bucket's custom domain.
   * Falls back to `cmsUrl` when media is served by Payload directly (dev).
   */
  mediaUrl?: string
  /**
   * Workspace packages whose source Next must transpile.
   * The `@makleri/*` packages are always included.
   */
  transpilePackages?: string[]
  /**
   * Opt back in to Vercel Image Optimization.
   *
   * Off by default and it should stay off: every derivative size is already
   * generated by Sharp at upload time and stored in R2, so Vercel's optimizer
   * would re-process images we have already paid to process once.
   */
  optimizeImages?: boolean
  /** Escape hatch merged last, so a client repo can still override anything. */
  extend?: NextConfig
}

const MAKLERI_PACKAGES = [
  '@makleri/core',
  '@makleri/ui',
] as const

/**
 * Headers applied to every route on every generated site.
 *
 * Intentionally excludes Content-Security-Policy: a per-site CSP depends on
 * which embeds that realtor uses (Google Maps, YouTube, virtual tours), so it
 * belongs in `extend` rather than here where a wrong value would break 80 sites.
 */
const SECURITY_HEADERS = [
  { key: 'X-Content-Type-Options', value: 'nosniff' },
  { key: 'X-Frame-Options', value: 'SAMEORIGIN' },
  { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
  { key: 'X-DNS-Prefetch-Control', value: 'on' },
  {
    key: 'Strict-Transport-Security',
    value: 'max-age=63072000; includeSubDomains; preload',
  },
  {
    key: 'Permissions-Policy',
    value: 'camera=(), microphone=(), geolocation=(), interest-cohort=()',
  },
]

function toRemotePattern(origin: string) {
  const url = new URL(origin)
  return {
    protocol: url.protocol.replace(':', '') as 'http' | 'https',
    hostname: url.hostname,
    ...(url.port ? { port: url.port } : {}),
  }
}

/**
 * Builds the Next.js config for a generated client site.
 *
 * A client repo's `next.config.ts` is three lines delegating here, which is what
 * makes a security-header change or a new media origin a package bump rather
 * than an edit across every client repo.
 */
export function createNextConfig(input: NextConfigInput): NextConfig {
  const { cmsUrl, mediaUrl, transpilePackages = [], optimizeImages = false, extend = {} } = input

  const imageOrigins = [mediaUrl ?? cmsUrl, cmsUrl]
  const remotePatterns = [...new Set(imageOrigins)].map(toRemotePattern)

  const base: NextConfig = {
    reactStrictMode: true,
    poweredByHeader: false,

    transpilePackages: [...MAKLERI_PACKAGES, ...transpilePackages],

    images: optimizeImages
      ? { remotePatterns, formats: ['image/avif', 'image/webp'] }
      : { unoptimized: true, remotePatterns },

    async headers() {
      const fromExtend = (await extend.headers?.()) ?? []
      return [{ source: '/:path*', headers: SECURITY_HEADERS }, ...fromExtend]
    },
  }

  // `extend` wins on every key except `headers`, which is merged above so a
  // client adding one header cannot silently drop the security baseline.
  const { headers: _extendHeaders, ...extendRest } = extend

  return { ...base, ...extendRest, headers: base.headers }
}

export { SECURITY_HEADERS }
