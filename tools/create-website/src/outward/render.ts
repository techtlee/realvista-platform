import { OUTWARD_ENABLED, type Json, type PlannedCommand } from '../types.js'
import { OUTWARD_ADAPTERS } from './adapters.js'
import { formatRecord } from './dns.js'
import type { CommandDir, OutwardCommand, OutwardInput, OutwardPlan, ProductionSecretFile } from './types.js'

/**
 * Renders the outward plans into `outward-plan.md` (for Josef) and
 * `outward-plan.json` (for tools), and converts commands to the engine's
 * `PlannedCommand`. Pure string work: nothing here executes or reads a secret.
 */

const SAFE = /^[A-Za-z0-9_./:=@%+,-]+$/
export const shellQuote = (s: string): string => (SAFE.test(s) ? s : `'${s.replace(/'/g, `'\\''`)}'`)

function dirOf(i: OutwardInput, d: CommandDir): string {
  return d === 'root' ? '' : i.dirs[d]
}

/** Path of a production secret file relative to the config root. */
export function secretFilePath(i: OutwardInput, f: ProductionSecretFile): string {
  const [repo, name] = f.split('/') as ['backend' | 'site', string]
  return `${i.dirs[repo]}/${name}`
}

/** One shell line. Secrets appear only as `cw secret-pipe` references or sourced files. */
export function commandLine(i: OutwardInput, c: OutwardCommand): string {
  const env = Object.entries(c.env ?? {}).map(([k, v]) => `${k}=${shellQuote(v)}`)
  let line = [...env, ...c.argv.map(shellQuote)].join(' ')
  if (c.envFrom?.length) {
    const src = c.envFrom.map((f) => `. "$CW_ROOT/${secretFilePath(i, f)}"`).join('; ')
    line = `(set -a; ${src}; set +a; ${line})`
  }
  if (c.stdin?.kind === 'secret') line = `cw secret-pipe ${i.slug} ${c.stdin.file} ${c.stdin.key} | ${line}`
  else if (c.stdin?.kind === 'shell-var') line = `printf %s "$${c.stdin.name}" | ${line}`
  else if (c.stdin?.kind === 'value') line = `printf %s ${shellQuote(c.stdin.value)} | ${line}`
  if (c.captureTo) {
    const jq = c.captureTo.jq ? ` | jq -r ${shellQuote(c.captureTo.jq)}` : ''
    line = `${line}${jq} | cw secret-pipe --write ${i.slug} ${c.captureTo.file} ${c.captureTo.key}`
  }
  if (c.idempotencyProbe) line = `${c.idempotencyProbe.map(shellQuote).join(' ')} >/dev/null 2>&1 || ${line}`
  return line
}

/**
 * The engine's PlannedCommand, for state and `cw plan --json`.
 *
 * `PlannedCommand.stdin` is a `SecretRef` to a *local* secret file, and an
 * outward command never reads one (production values are separate), so it is
 * left unset and the production source is spelled out in `note` instead.
 */
export function toPlannedCommand(i: OutwardInput, c: OutwardCommand): PlannedCommand {
  const notes = [
    c.note,
    c.envFrom?.length ? `environment from ${c.envFrom.join(', ')}` : undefined,
    c.stdin?.kind === 'secret' ? `stdin: ${c.stdin.key} from ${c.stdin.file}` : undefined,
    c.stdin?.kind === 'shell-var' ? `stdin: $${c.stdin.name}` : undefined,
    c.captureTo ? `stdout stored as ${c.captureTo.key} in ${c.captureTo.file}` : undefined,
    c.cwd === 'root' ? undefined : `run in ${dirOf(i, c.cwd)}`,
  ].filter((n): n is string => !!n)
  return {
    id: c.id,
    description: c.description,
    argv: [...c.argv],
    envNames: [...Object.keys(c.env ?? {}), ...(c.stdin?.kind === 'shell-var' ? [c.stdin.name] : [])],
    ...(c.idempotencyProbe ? { idempotencyProbe: [...c.idempotencyProbe] } : {}),
    ...(notes.length ? { note: notes.join('; ') } : {}),
  }
}

export function planAll(i: OutwardInput): OutwardPlan[] {
  return OUTWARD_ADAPTERS.map((a) => a.plan(i))
}

export function renderOutwardPlanMarkdown(i: OutwardInput, plans: OutwardPlan[] = planAll(i)): string {
  const out: string[] = [
    `# Outward plan: ${i.slug}`,
    '',
    'Generated by `/create-website` in local mode. **Nothing below has been run**: outward steps are',
    'disabled in this phase, and the lead runs them by hand, in this order.',
    '',
    `- \`${i.owner}\` is the GitHub org or user and \`${i.team}\` the Vercel team slug. Replace both.`,
    '- `$CW_ROOT` is the directory holding `create-website.config.json`.',
    '- Secrets appear only as references. `cw secret-pipe` reads, writes or generates one value of a',
    '  production secret file without showing it. It is a documented placeholder in this phase and',
    '  refuses in local mode.',
    `- Production secrets are new values in \`${secretFilePath(i, 'backend/.env.production.local')}\` and`,
    `  \`${secretFilePath(i, 'site/.env.production.local')}\` (git-ignored), never the local dev ones.`,
    '',
    '| Runbook | Step | What |',
    '|---|---|---|',
    ...plans.map((p) => `| ${p.runbook} | \`${p.step}\` | ${p.title}${p.notNeeded ? ' (not needed)' : ''} |`),
  ]

  for (const p of plans) {
    out.push('', `## ${p.runbook}. ${p.title} (\`${p.step}\`)`, '', p.summary)
    if (p.notNeeded) out.push('', p.notNeeded)
    if (p.commands.length) {
      out.push('', '```sh')
      let cwd: string | undefined
      for (const c of p.commands) {
        const d = dirOf(i, c.cwd)
        if (d !== cwd) {
          out.push(d ? `cd "$CW_ROOT/${d}"` : 'cd "$CW_ROOT"')
          cwd = d
        }
        out.push(`# ${c.description}`, commandLine(i, c))
      }
      out.push('```')
      const notes = p.commands.filter((c) => c.note)
      if (notes.length) out.push('', ...notes.map((c) => `- \`${c.id}\`: ${c.note}`))
    }
    if (p.records?.length) out.push('', '```', ...p.records.map(formatRecord), '```')
    if (p.instructions.length) out.push('', ...p.instructions.map((s) => `- ${s}`))
  }
  return `${out.join('\n')}\n`
}

export function renderOutwardPlanJson(i: OutwardInput, plans: OutwardPlan[] = planAll(i)): Json {
  return {
    planVersion: 1,
    slug: i.slug,
    mode: 'local',
    outwardEnabled: OUTWARD_ENABLED,
    steps: plans.map((p) => ({
      step: p.step,
      title: p.title,
      runbook: p.runbook,
      summary: p.summary,
      notNeeded: p.notNeeded ?? null,
      commands: p.commands.map((c) => ({
        ...(toPlannedCommand(i, c) as unknown as { [k: string]: Json }),
        shell: commandLine(i, c),
      })),
      records: (p.records ?? []).map((r) => ({ type: r.type, host: r.host, value: r.value, project: r.project })),
      instructions: p.instructions,
    })),
  }
}
