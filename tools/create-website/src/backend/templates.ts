/**
 * Files the backend copy gets on top of the pristine template (runbook F14 and
 * step 18). Pure functions: no secrets, no ports that are not already public
 * in the state file.
 */
import type { ProvisioningRequest } from '../types.js'

export function renderBackendReadme(o: {
  request: ProvisioningRequest
  cmsCommit: string
  backendPort: number
  subdomainBase: string
}): string {
  const { request: r } = o
  const brand = r.provisioning.brand.name
  const domain = r.provisioning.domain?.name
  const admin = domain && r.provisioning.domain?.situation !== 'none' ? `admin.${domain}` : `admin.${r.slug}.${o.subdomainBase}`
  return `# backend-${r.slug}

Admin (CMS) for **${brand}**, a REALVISTA client. Generated by \`/create-website\`
from the \`realvista-client-backend\` template (cms ${o.cmsCommit.slice(0, 7)}); the first
commit is the unmodified template, so every client-specific change is a visible diff.

- Production address: https://${admin} (fallback https://admin.${r.slug}.${o.subdomainBase})
- Website repo: \`site-${r.slug}\`
- Local: \`pnpm dev --port ${o.backendPort}\`, admin at http://localhost:${o.backendPort}/admin

## Local secrets (git-ignored, never commit or print them)

- \`.env\`: \`DATABASE_URL\`, \`PAYLOAD_SECRET\`, \`PORT\`, \`PLATFORM_SUBDOMAIN_BASE\`
- \`.admin-credentials.local\`: platform-admin and realtor logins, \`REVALIDATE_SECRET\`, the site's API key

## Scripts

| Script | What |
|---|---|
| \`pnpm migrate\` | apply migrations |
| \`pnpm seed:admin\` | platform-admin login (upsert) |
| \`pnpm seed:client-site\` | tenant + starter content (replaces content, keeps users) |
| \`pnpm seed:client\` | the realtor's login (upsert) |
| \`pnpm seed:site-key\` | the website's read-only API key |

Security updates: Dependabot (\`.github/dependabot.yml\`) opens weekly PRs; merge them.
`
}

/** Same policy as client #1's repos: weekly npm, Next/React and Payload grouped. */
export function renderDependabot(kind: 'backend' | 'site'): string {
  const groups =
    kind === 'backend'
      ? `      next-react:
        patterns: ['next', 'react', 'react-dom', '@types/react', '@types/react-dom']
      payload:
        patterns: ['payload', '@payloadcms/*']
`
      : `      next-react:
        patterns: ['next', 'react', 'react-dom', '@types/react', '@types/react-dom']
`
  return `# Security and framework updates for a per-client deployment (ARCHITECTURE.md,
# "The accepted cost: security updates"). GitHub opens the PR, we merge,
# Vercel redeploys.
version: 2
updates:
  - package-ecosystem: npm
    directory: /
    schedule:
      interval: weekly
    open-pull-requests-limit: 5
    groups:
${groups}`
}
